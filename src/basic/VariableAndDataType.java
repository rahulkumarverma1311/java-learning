package basic;

public class VariableAndDataType {
    public static void main(String[] args) {
        // Integer ----> byte short int long

//        byte b= 0b101;
//        byte b =05;
        byte b = 0XA;
        short s =10;
        int i =100;
        long l =1000;
        System.out.println("integers->>> "+ b+","+" "+ s+" "+ i+" "+ l);

        // decimal number

        float f = 120.23f;
        double d = 47632.231;
        System.out.println("decimal->>> "+ f +" "+ d);


        // char
        char a ='a';

        System.out.println("character->>> "+ a);


        // boolean

        boolean flag = true;
        System.out.println("boolean->>> "+ flag);


    }
}
